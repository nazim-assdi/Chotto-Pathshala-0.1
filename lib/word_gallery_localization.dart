String localizeWordGalleryMeaning(String bangla) {
  final values = wordGalleryMeaningTranslations[bangla];
  if (values == null) return bangla;
  switch (AppLanguageController.selected.value) {
    case 'English':
      return values[0];
    case 'العربية':
      return values[1];
    default:
      return bangla;
  }
}

String localizeGalleryNumberName(int number) {
  if (number < 1 || number > _galleryNumberNames.length)
    return number.toString();
  final locale = AppLanguageController.selected.value;
  final index = locale == 'English'
      ? 1
      : locale == 'العربية'
      ? 2
      : 0;
  return _galleryNumberNames[number - 1][index];
}

String localizeGalleryDigits(int number) {
  final locale = AppLanguageController.selected.value;
  final symbols = locale == 'বাংলা'
      ? '০১২৩৪৫৬৭৮৯'
      : locale == 'العربية'
      ? '٠١٢٣٤٥٦٧٨٩'
      : '0123456789';
  return number.toString().split('').map((digit) {
    final value = int.tryParse(digit);
    return value == null ? digit : symbols[value];
  }).join();
}
